"""Stroke font (garis-tengah) untuk tracing: satu goresan per bagian huruf.

Koordinat: y ke atas, baseline y=0, tinggi huruf kapital = 1.0, x-height = 0.75, descender ~ -0.22.
Satuan = tinggi kapital (mm sebenarnya ditentukan layout). Tiap glyph = (lebar_tinta, [goresan]);
tiap goresan = daftar titik (polyline). Bentuknya mengikuti DejaVu Sans (termasuk 'a' dua lantai)
supaya cocok dengan huruf contoh (outline). Jika Anda memakai font tracing lain (fonts/Trace.ttf),
sesuaikan data ini atau set config.TRACE_STYLE = "outline".
"""
from __future__ import annotations

import math
from typing import Dict, List, Sequence, Tuple, Union

Pt = Tuple[float, float]
Stroke = List[Pt]
Part = Union[Pt, Sequence[Pt]]


def arc(cx: float, cy: float, rx: float, ry: float, a0: float, a1: float, step: float = 6.0) -> Stroke:
    """Busur elips dari sudut a0 ke a1 (derajat; + = berlawanan arah jarum jam; y ke atas)."""
    n = max(2, int(abs(a1 - a0) / step))
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n))) for i in range(n + 1)]


def P(*parts: Part) -> Stroke:
    """Gabungkan titik/daftar titik menjadi satu goresan."""
    out: Stroke = []
    for p in parts:
        if isinstance(p[0], (int, float)):
            out.append(p)  # type: ignore[arg-type]
        else:
            out.extend(p)  # type: ignore[arg-type]
    return out


def _rot180(w: float, strokes: List[Stroke]) -> List[Stroke]:
    return [[(w - x, 1.0 - y) for x, y in s][::-1] for s in strokes]


XH = 0.75
GLYPHS: Dict[str, Tuple[float, List[Stroke]]] = {}


def _g(ch: str, w: float, *strokes: Stroke) -> None:
    GLYPHS[ch] = (w, list(strokes))


